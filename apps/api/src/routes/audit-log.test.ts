import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { authenticator } from 'otplib';
import sharp from 'sharp';
import type { FastifyInstance } from 'fastify';
import { createFakeClock, systemClock, toDhakaDate } from '@barakah/shared';
import { buildApp } from '../app';
import { generateDues } from '../dues/service';
import { postEntries, reverseEntry } from '../ledger/service';
import { inTransaction } from '../lib/tx';
import { createTestDb, type TestDb } from '../test/db-harness';
import {
  GOOD_PIN,
  activateSession,
  seedFund,
  testEnv,
  type Fund,
  type TestSession,
} from '../test/fund-fixture';
import { multipartBody } from '../test/multipart';
import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

// The real clock: TOTP codes generated by the test are checked against the app's clock.
const clock = systemClock;
// Business logic that needs a known date (dues, reversals) gets a fixed one.
const fixedClock = createFakeClock(new Date('2026-11-05T03:00:00Z'));

let db: TestDb | null;
let app: FastifyInstance;
let fund: Fund;
const s = {} as Record<'M01' | 'M02' | 'M03' | 'M04' | 'M07', TestSession>;

const call = (
  method: 'GET' | 'POST' | 'PATCH' | 'DELETE',
  url: string,
  who?: string,
  payload?: Record<string, unknown>,
) =>
  app.inject({
    method,
    url: `/api/v1${url}`,
    ...(who ? { headers: { authorization: `Bearer ${who}` } } : {}),
    ...(payload ? { payload } : {}),
  });

const auditCount = async () =>
  Number(
    ((await db!.admin.query(`SELECT count(*) AS n FROM audit_log`)).rows[0] as { n: string }).n,
  );

beforeAll(async () => {
  db = await createTestDb();
  if (!db) return;
  app = await buildApp({
    env: { ...testEnv, FILES_DIR: mkdtempSync(join(tmpdir(), 'barakah-audit-')) },
    db: db.app,
    clock,
  });
  fund = await seedFund(db.admin);
  for (const code of ['M01', 'M02', 'M03', 'M04', 'M07'] as const) {
    s[code] = await activateSession(app, db, clock, fund, code);
  }
}, 180_000);

afterAll(async () => {
  await app?.close();
  await db?.close();
});

function dbIt(name: string, fn: () => Promise<void>): void {
  it(name, async (ctx) => {
    if (!db) return ctx.skip();
    await fn();
  });
}

type Item = Record<string, unknown> & { id: string; action: string };
const list = async (qs = '', who = s.M01.access_token) => {
  const res = await call('GET', `/audit-log${qs}`, who);
  expect(res.statusCode, res.body).toBe(200);
  return res.json() as { items: Item[]; next_cursor: string | null };
};

describe('GET /audit-log access', () => {
  dbIt(
    'needs a login, and members get 403: only the cashier and the auditor may read it',
    async () => {
      expect((await call('GET', '/audit-log')).statusCode).toBe(401);
      for (const who of [s.M02, s.M03]) {
        const res = await call('GET', '/audit-log', who.access_token);
        expect(res.statusCode).toBe(403);
        expect(res.json().code).toBe('auth.forbidden');
      }
      expect((await call('GET', '/audit-log', s.M01.access_token)).statusCode).toBe(200);
      expect((await call('GET', '/audit-log', s.M07.access_token)).statusCode).toBe(200);
    },
  );

  dbIt('reading the audit log writes nothing and never exposes a PIN', async () => {
    const before = await auditCount();
    const body = (await call('GET', '/audit-log?limit=200', s.M07.access_token)).body;
    expect(await auditCount()).toBe(before);
    expect(body).not.toContain(GOOD_PIN);
    expect(body).not.toMatch(/pin_hash|argon2/);
  });
});

describe('GET /audit-log contents', () => {
  dbIt('lists newest first with the actor, entity, device and ip', async () => {
    const { items } = await list('?limit=200');
    const ids = items.map((i) => BigInt(i.id));
    expect(ids).toEqual([...ids].sort((a, b) => (a < b ? 1 : -1)));
    const activation = items.find(
      (i) => i.action === 'auth.activate' && i['actor_code'] === 'M02',
    )!;
    expect(activation).toMatchObject({
      actor_user_id: fund.users.M02,
      entity_type: 'user',
      entity_id: fund.users.M02,
      ip: expect.stringMatching(/\d/) as string,
      device_id: s.M02.device_id,
    });
    expect(activation['after']).toMatchObject({ platform: 'android', mode: 'replace' });
  });

  dbIt('filters by action, entity, actor and Asia/Dhaka day', async () => {
    const activations = (await list('?action=auth.activate&limit=200')).items;
    expect(activations).toHaveLength(5);
    expect(activations.every((i) => i.action === 'auth.activate')).toBe(true);

    const one = (await list(`?entity_id=${fund.users.M03}&action=auth.activate`)).items;
    expect(one).toHaveLength(1);

    const byActor = (await list(`?actor_user_id=${fund.users.M04}&limit=200`)).items;
    expect(byActor.length).toBeGreaterThan(0);
    expect(byActor.every((i) => i['actor_code'] === 'M04')).toBe(true);

    expect(
      (await list('?entity_type=user&limit=200')).items.every((i) => i['entity_type'] === 'user'),
    ).toBe(true);

    const today = toDhakaDate(new Date());
    const tomorrow = toDhakaDate(new Date(Date.now() + 24 * 3600_000));
    const yesterday = toDhakaDate(new Date(Date.now() - 24 * 3600_000));
    expect((await list(`?from=${today}&to=${today}&limit=200`)).items.length).toBeGreaterThan(0);
    expect((await list(`?from=${tomorrow}`)).items).toEqual([]);
    expect((await list(`?to=${yesterday}`)).items).toEqual([]);
    expect((await call('GET', '/audit-log?from=2026-02-30', s.M01.access_token)).statusCode).toBe(
      400,
    );
  });

  dbIt('pages with cursors: every row once, none missed', async () => {
    const total = await auditCount();
    const seen: string[] = [];
    let cursor: string | null = null;
    do {
      const page: { items: Item[]; next_cursor: string | null } = await list(
        `?limit=7${cursor ? `&cursor=${encodeURIComponent(cursor)}` : ''}`,
      );
      seen.push(...page.items.map((i) => i.id));
      cursor = page.next_cursor;
    } while (cursor);
    // Listing itself writes nothing, so the walk sees exactly the rows that exist.
    expect(seen).toHaveLength(total);
    expect(new Set(seen).size).toBe(total);
    expect((await call('GET', '/audit-log?cursor=zzz', s.M01.access_token)).json().code).toBe(
      'request.invalid_cursor',
    );
  });
});

describe('what is audited (spec 4 and 19.4)', () => {
  dbIt('security and device views are sensitive reads and are logged', async () => {
    const seen = async (action: string) =>
      (await list(`?action=${action}&actor_user_id=${fund.users.M02}`)).items.length;
    const devices = await seen('security.view_devices');
    const events = await seen('security.view_device_events');
    expect((await call('GET', '/me/devices', s.M02.access_token)).statusCode).toBe(200);
    expect((await call('GET', '/device-events', s.M02.access_token)).statusCode).toBe(200);
    expect(await seen('security.view_devices')).toBe(devices + 1);
    expect(await seen('security.view_device_events')).toBe(events + 1);
  });

  dbIt(
    'ordinary reads (members, ledger, dues, rules, balances, votes) write no audit rows',
    async () => {
      const before = await auditCount();
      for (const url of [
        '/me',
        '/members',
        `/members/${fund.members.M03}`,
        '/share-register',
        '/share-holdings',
        '/rules',
        '/accounts/balances',
        '/dues',
        '/fines',
        '/ledger',
        '/ledger/verify',
      ]) {
        expect((await call('GET', url, s.M02.access_token)).statusCode, url).toBe(200);
      }
      expect(await auditCount()).toBe(before);
    },
  );

  dbIt('every write leaves an audit row naming the action', async () => {
    const cashier = s.M01.access_token;
    const png = await sharp({ create: { width: 8, height: 8, channels: 3, background: '#fff' } })
      .png()
      .toBuffer();
    const upload = multipartBody([
      { name: 'file', filename: 'x.png', contentType: 'image/png', data: png },
    ]);
    let totpSecret = '';

    const writes: Array<[string, () => Promise<unknown>]> = [
      [
        'auth.login',
        () =>
          call('POST', '/auth/login', undefined, {
            member_ref: 'M02',
            pin: GOOD_PIN,
            device_id: s.M02.device_id,
          }),
      ],
      [
        'member.update_profile',
        () => call('PATCH', '/members/me', s.M02.access_token, { notify_prefs: { digits: 'en' } }),
      ],
      [
        'member.update_contact',
        () =>
          call('PATCH', `/members/${fund.members.M05}/contact`, cashier, { full_name: 'Renamed' }),
      ],
      [
        'file.upload',
        () =>
          app.inject({
            method: 'POST',
            url: '/api/v1/files',
            payload: upload.payload,
            headers: {
              authorization: `Bearer ${s.M02.access_token}`,
              'content-type': upload.contentType,
            },
          }),
      ],
      [
        'auth.totp_enroll_started',
        async () => {
          const res = await call('POST', '/auth/totp/enroll', cashier);
          totpSecret = (res.json() as { secret: string }).secret;
        },
      ],
      [
        'auth.totp_enrolled',
        () =>
          call('POST', '/auth/totp/verify', cashier, { code: authenticator.generate(totpSecret) }),
      ],
      [
        'auth.step_up',
        () =>
          call('POST', '/auth/totp/verify', cashier, { code: authenticator.generate(totpSecret) }),
      ],
      [
        'auth.activation_code_issued',
        () =>
          call('POST', `/members/${fund.members.M06}/activation-code`, cashier, {
            mode: 'replace',
          }),
      ],
      ['auth.unlock', () => call('POST', `/members/${fund.members.M02}/unlock`, cashier)],
      [
        'dues.generate',
        () => generateDues({ pool: db!.app, clock: fixedClock }, { period: '2026-10' }),
      ],
      [
        'ledger.reverse',
        async () => {
          await inTransaction(db!.app, async (tx) => {
            const [e] = await postEntries(
              tx,
              [
                {
                  entry_date: '2026-10-05',
                  debit: 'CASH',
                  credit: 'MEMBER_CAPITAL',
                  amount_paisa: 1n,
                  ref_type: 'payment',
                },
              ],
              { userId: fund.users.M01 },
            );
            await reverseEntry(tx, e!.seq, {
              reason: 'test reversal',
              actor: { userId: fund.users.M01 },
              clock: fixedClock,
            });
          });
        },
      ],
      ['auth.logout', () => call('POST', '/auth/logout', s.M03.access_token)],
      [
        'auth.device_revoked',
        () => call('DELETE', `/me/devices/${s.M04.device_id}`, s.M04.access_token),
      ],
    ];

    for (const [action, run] of writes) {
      const before = await auditCount();
      const res = (await run()) as { statusCode?: number } | undefined;
      if (res?.statusCode !== undefined) {
        expect(res.statusCode, `${action} should succeed`).toBeLessThan(300);
      }
      expect(await auditCount(), `${action} wrote an audit row`).toBeGreaterThan(before);
      const latest = await db!.admin.query(`SELECT action FROM audit_log ORDER BY id DESC LIMIT 5`);
      expect(
        (latest.rows as Array<{ action: string }>).map((r) => r.action),
        action,
      ).toContain(action);
    }
  });

  dbIt(
    'no audit row holds a PIN, an activation code, a refresh token or a TOTP secret',
    async () => {
      const all = JSON.stringify(
        (await db!.admin.query(`SELECT before, after FROM audit_log`)).rows,
      );
      expect(all).not.toContain(GOOD_PIN);
      for (const session of Object.values(s)) {
        expect(all).not.toContain(session.refresh_token);
        expect(all).not.toContain(session.access_token);
      }
      expect(all).not.toMatch(/totp_secret|"secret"/);
    },
  );
});
