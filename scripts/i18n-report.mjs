// Writes docs/BENGALI-REVIEW.md: every user-facing string, Bengali beside English, with the doubtful ones first.
//   pnpm i18n:report
// A Bengali speaker reads it top to bottom and marks anything that sounds wrong; the fix is made in
// packages/shared/src/i18n/bn.json. Re-run after changing strings.
import { readFileSync, writeFileSync } from 'node:fs';

const load = (name) => JSON.parse(readFileSync(new URL(`../packages/shared/src/i18n/${name}.json`, import.meta.url), 'utf8'));
const flat = (o, p = '') => Object.entries(o).flatMap(([k, v]) => (v && typeof v === 'object' ? flat(v, `${p}${k}.`) : [[`${p}${k}`, String(v)]]));
const bn = Object.fromEntries(flat(load('bn')));
const en = Object.fromEntries(flat(load('en')));
const keys = Object.keys(bn).sort();

const hasBengali = (s) => /[ঀ-৿]/.test(s);
const KNOWN = ['bKash', 'Nagad', 'PDF', 'ZIP', 'CSV', 'TrxID', 'SMS', 'PIN', 'TOTP', 'APK', 'QR', 'NAV', 'age'];
const latinWords = (s) => (s.replace(/\{\{?\w+\}?\}/g, '').match(/[A-Za-z][A-Za-z']{2,}/g) ?? []).filter((w) => !KNOWN.includes(w));
const cell = (s) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');

const same = keys.filter((k) => bn[k] === en[k] && /[A-Za-z]{3,}/.test(bn[k]));
const mixed = keys.filter((k) => hasBengali(bn[k]) && latinWords(bn[k]).length > 0);
const long = keys.filter((k) => bn[k].length > 140);

const row = (k) => `| \`${k}\` | ${cell(bn[k])} | ${cell(en[k])} |`;
const table = (list) => ['| Key | বাংলা | English |', '| --- | --- | --- |', ...list.map(row)].join('\n');

const sections = new Map();
for (const k of keys) {
  const top = k.split('.')[0];
  if (!sections.has(top)) sections.set(top, []);
  sections.get(top).push(k);
}

const out = [
  '# Bengali copy review',
  '',
  `Generated by \`pnpm i18n:report\` from \`packages/shared/src/i18n\`. ${keys.length} strings.`,
  '',
  'How to review: read the **বাংলা** column. Does it sound natural to a member of the fund? Is the tone polite and consistent (আপনি throughout)? Is the meaning the same as the English? Note the key of anything to change and fix it in `bn.json`.',
  '',
  'Rules already enforced by tests: both languages have exactly the same keys and `{placeholders}`; Nagad is always written "Nagad" and cash is "হাতে নগদ" (the word নগদ alone is ambiguous).',
  '',
  '## Look at these first',
  '',
  `### Same as English (${same.length}) — fine for brand names and codes, otherwise needs translating`,
  '',
  same.length ? table(same) : '_None._',
  '',
  `### English words inside Bengali text (${mixed.length})`,
  '',
  mixed.length
    ? ['| Key | বাংলা | English words |', '| --- | --- | --- |', ...mixed.map((k) => `| \`${k}\` | ${cell(bn[k])} | ${latinWords(bn[k]).join(', ')} |`)].join('\n')
    : '_None._',
  '',
  `### Long strings (${long.length}) — check they are not too heavy for a small screen`,
  '',
  long.length ? table(long) : '_None._',
  '',
  '## Everything, by screen',
  '',
  ...[...sections].flatMap(([name, list]) => [`### ${name} (${list.length})`, '', table(list), '']),
].join('\n');

writeFileSync(new URL('../docs/BENGALI-REVIEW.md', import.meta.url), `${out}\n`);
console.log(`docs/BENGALI-REVIEW.md written: ${keys.length} strings, ${same.length} same as English, ${mixed.length} with English words, ${long.length} long`);
